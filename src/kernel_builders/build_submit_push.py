"""Assemble the SUBMIT kernel push dir: offline zarr + T4 + data resolver.

The submit notebook (kaggle/biohub_submit.ipynb) is generated by
kaggle/build_notebook.py and already contains the offline-zarr install and the
find_data_root() resolver. Here we only need to wrap it with correct kernel
metadata (T4, wheels dataset, competition data) and a fresh id.
"""
import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

src = ROOT / "kaggle" / "biohub_submit.ipynb"
nb = json.load(open(src))
# Compile-check every code cell before pushing.
for i, c in enumerate(nb["cells"]):
    if c["cell_type"] == "code":
        compile("".join(c["source"]), f"<cell {i}>", "exec")
print("submit notebook cells compile")

out_dir = HERE / "submit"
out_dir.mkdir(parents=True, exist_ok=True)
json.dump(nb, open(out_dir / "biohub-cell-tracking-submit.ipynb", "w"), indent=1)

meta = {
    "id": "eeshsaxena/biohub-cell-tracking-submit",
    "title": "Biohub Cell Tracking Submit",
    "code_file": "biohub-cell-tracking-submit.ipynb",
    "language": "python", "kernel_type": "notebook",
    "is_private": True, "enable_gpu": True, "enable_tpu": False,
    "enable_internet": False,
    "machine_shape": "NvidiaTeslaT4",
    "keywords": [],
    "dataset_sources": ["eeshsaxena/biohub-zarr-wheels"],
    "kernel_sources": [],
    "competition_sources": ["biohub-cell-tracking-during-development"],
    "model_sources": [],
}
json.dump(meta, open(out_dir / "kernel-metadata.json", "w"), indent=2)
print("wrote", out_dir)
